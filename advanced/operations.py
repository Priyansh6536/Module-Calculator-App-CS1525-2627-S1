def add(number_1: float|int, number_2: float|int) -> float|int:
    """Adds and returns the sum of two numbers.

    :param number_1: First number in the addition equation.
    :param number_2: Second number in the addition equation.
    :return: The sum of the two numbers.
    """

    return number_1 + number_2

def subtract(number_1: float|int, number_2: float|int) -> float|int:
    """Subtracts and returns the difference two numbers.

    :param number_1: First number in the subtraction equation.
    :param number_2: Second number in the subtraction equation.
    :return: The difference of the two numbers.
    """
    return number_1 - number_2

def multiply(number_1: float|int, number_2: float|int) -> float|int:
    """Multiples and returns the product of two numbers.

    :param number_1: First number in the multiplication equation.
    :param number_2: Second number in the multiplication equation.
    :return: The product of the two numbers.
    """
    return number_1 * number_2

def divide(number_1: float|int, number_2: float|int) -> float|int:
    """Divides and returns the quotient of a number.


    :param number_1: The dividend of the division equation.
    :param number_2: The divisor of the division equation.
    :return: The quotient of the two numbers.
    """
    return number_1 / number_2